const GAPS = 9;

/** Scroll-driven explainer: as you scroll the interpolation factor climbs and more frames fill every gap. */
export const FramesDemo = () => {
  const ref = useRef<HTMLElement>(null);
  const [factor, setFactor] = useState(1);
  useScrollVar(ref, "sticky", (p) => setFactor(1 + Math.min(7, Math.floor(p * 8))));

  return (
    <section ref={ref} className="relative h-[320vh]">
      <div className="sticky top-0 flex h-screen flex-col justify-center overflow-hidden px-5 sm:px-10">
        <StatueBackdrop src={STATUES[1]} side="left" />
        <p className="relative z-10 mb-3 font-mono text-[11px] uppercase tracking-widest text-ink-dim">
          01 / What happens to your video
        </p>
        <p className="relative z-10 font-display text-[clamp(6rem,22vw,18rem)] leading-none">
          {24 * factor}
          <span className="ml-3 text-[0.22em] text-ink-dim">
            FPS · {factor}×
          </span>
        </p>

        <div className="relative z-10 mt-10 flex items-end">
          {Array.from({ length: GAPS }, (_, g) => (
            <div key={g} className="flex flex-1 items-end">
              <div className="h-24 w-3 shrink-0 bg-ink sm:h-32 sm:w-5" title="Original frame" />
              <div className="flex flex-1 items-end justify-evenly">
                {Array.from({ length: factor - 1 }, (_, k) => (
                  <div key={k} className="dither-frame h-16 w-1.5 shrink-0 sm:h-24 sm:w-3" title="Generated frame" />
                ))}
              </div>
            </div>
          ))}
          <div className="h-24 w-3 shrink-0 bg-ink sm:h-32 sm:w-5" />
        </div>
        <div className="relative z-10 mt-4 flex gap-6 font-mono text-[10px] uppercase tracking-widest text-ink-dim">
          <span className="flex items-center gap-2">
            <i className="inline-block size-3 bg-ink" /> Your frames
          </span>
          <span className="flex items-center gap-2">
            <i className="dither-frame inline-block size-3" /> Generated by InfiniteFlow
          </span>
        </div>
      </div>
    </section>
  );
};

